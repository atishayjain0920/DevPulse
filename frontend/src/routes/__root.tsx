// Tune the QueryClient defaults centrally so every hook inherits sensible
// caching + retry behaviour for the DevPulse API. Applied inside `getRouter`.
export function configureDefaultQueryClient(qc: QueryClient) {
  qc.setDefaultOptions({
    queries: {
      staleTime: 30_000,
      gcTime: 5 * 60_000,
      refetchOnWindowFocus: false,
      retry: (failureCount, error) => {
        // Never retry auth failures — the app should redirect instead.
        const status =
          error && typeof error === "object" && "status" in error
            ? Number((error as { status: unknown }).status)
            : 0;
        if (status === 401 || status === 403 || status === 404) return false;
        return failureCount < 2;
      },
    },
    mutations: { retry: 0 },
  });
}
